import random
import torch
import numpy as np
import albumentations as A
import cv2
from torch.utils.data import Dataset

torch.manual_seed(42)
np.random.seed(42)
random.seed(42)
print("Setup complete and seeds set.")

def get_degradation_pipeline(severity_level=1):
    blur_limit = (3 + 2 * severity_level, 3 + 2 * severity_level)
    scale_factor = max(0.5, 1.0 - (0.15 * severity_level))

    return A.Compose([
        A.GaussianBlur(blur_limit=blur_limit, p=0.5),
        A.GaussNoise(var_limit=(0.01 * severity_level, 0.05 * severity_level), p=0.5),
        A.RandomScale(scale_limit=(scale_factor - 1.0, scale_factor - 1.0), p=0.5),
        A.ImageCompression(quality_lower=max(10, 90 - (20 * severity_level)), quality_upper=max(30, 100 - (10 * severity_level)), p=0.5)
    ])

class XBDDatasetWithDegradation(Dataset):
    def __init__(self, pre_images, post_images, labels, transform=None, degradation_transform=None):
        self.pre_images = pre_images
        self.post_images = post_images
        self.labels = labels
        self.transform = transform
        self.deg_transform = degradation_transform

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        pre_img = self.pre_images[idx]
        post_img = self.post_images[idx]
        label = self.labels[idx]

        if self.deg_transform:
            augmented_pre = self.deg_transform(image=pre_img)
            augmented_post = self.deg_transform(image=post_img)
            pre_img = augmented_pre['image']
            post_img = augmented_post['image']

        if self.transform:
            pre_img = self.transform(image=pre_img)['image']
            post_img = self.transform(image=post_img)['image']

        return {
            'pre_image': torch.tensor(pre_img, dtype=torch.float32),
            'post_image': torch.tensor(post_img, dtype=torch.float32),
            'label': torch.tensor(label, dtype=torch.long)
        }

pipeline = get_degradation_pipeline(severity_level=1)

dummy_pre = np.zeros((512, 512, 3), dtype=np.uint8)
dummy_post = np.zeros((512, 512, 3), dtype=np.uint8)
dummy_label = 2

dataset = XBDDatasetWithDegradation(
    pre_images=[dummy_pre],
    post_images=[dummy_post],
    labels=[dummy_label],
    degradation_transform=pipeline
)

sample = dataset[0]
print("Dataset test passed successfully. Output shape:", sample['pre_image'].shape)